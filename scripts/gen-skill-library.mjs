#!/usr/bin/env node
/**
 * Generates convex/skillLibrary.generated.ts from convex/skill-bodies/*.md.
 *
 * Each .md holds a real skill (YAML frontmatter: name + description, then the
 * markdown body). The generator emits the CURATED array as a TS module so the
 * Convex seed stays a faithful copy of the source bodies — edit the .md, rerun:
 *
 *   node scripts/gen-skill-library.mjs
 *
 * Triggers/origin/enabled/ordering are curated HERE (below), not in the .md.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const bodiesDir = join(here, "..", "convex", "skill-bodies");
const outFile = join(here, "..", "convex", "skillLibrary.generated.ts");

/** Curated per-slug metadata: slash-trigger words + ordering + default state. */
const META = {
  "frontend-design": {
    triggers: ["ui", "interface", "frontend", "component", "design", "landing", "dashboard"],
    origin: "anthropic",
    enabled: true,
  },
  "deep-research": {
    triggers: ["research", "sources", "compare", "investigate", "find out", "deep dive"],
    origin: "anthropic",
    enabled: true,
  },
  "code-review": {
    triggers: ["review", "audit this", "critique", "code review", "pr review"],
    origin: "anthropic",
    enabled: true,
  },
  "security-review": {
    triggers: ["security", "injection", "xss", "auth", "hardening", "owasp", "exploit"],
    origin: "anthropic",
    enabled: true,
  },
  brainstorm: {
    triggers: ["brainstorm", "idea", "options", "what if", "decide between", "choose"],
    origin: "anthropic",
    enabled: true,
  },
  "skill-creator": {
    triggers: ["create skill", "new skill", "improve skill", "skill"],
    origin: "anthropic",
    enabled: true,
  },
};

/** Display names (frontmatter names are slugs; the UI wants title case). */
const NAMES = {
  "frontend-design": "Frontend Design",
  "deep-research": "Deep Research",
  "code-review": "Code Review",
  "security-review": "Security Review",
  brainstorm: "Brainstorm",
  "skill-creator": "Skill Creator",
};

function parseFrontmatter(raw, file) {
  const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`${file}: missing frontmatter`);
  const name = m[1].match(/^name:\s*(.+)$/m)?.[1].trim();
  const description = m[1].match(/^description:\s*(.+)$/m)?.[1].trim();
  if (!name || !description) throw new Error(`${file}: frontmatter needs name + description`);
  return { name, description, body: m[2].trim() };
}

/** Escape a string for embedding in a TS template literal. */
function escTemplate(s) {
  return s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

const files = readdirSync(bodiesDir).filter((f) => f.endsWith(".md")).sort();
if (files.length === 0) throw new Error(`no .md skill bodies in ${bodiesDir}`);

const entries = [];
for (const f of files) {
  const slug = f.replace(/\.md$/, "");
  const meta = META[slug];
  if (!meta) throw new Error(`no curated META for ${slug} — add it to gen-skill-library.mjs`);
  const { description, body } = parseFrontmatter(readFileSync(join(bodiesDir, f), "utf8"), f);
  entries.push({ slug, name: NAMES[slug] ?? slug, description, body, ...meta });
}

const out = `/**
 * GENERATED by scripts/gen-skill-library.mjs from convex/skill-bodies/*.md.
 * Do NOT edit by hand — edit the .md body, then rerun the generator.
 */

export interface SkillLibrarySeed {
  slug: string;
  name: string;
  description: string;
  triggers: string[];
  body: string;
  origin: string;
  enabled: boolean;
}

export const CURATED: SkillLibrarySeed[] = [
${entries
  .map(
    (e) => `  {
    slug: ${JSON.stringify(e.slug)},
    name: ${JSON.stringify(e.name)},
    description: ${JSON.stringify(e.description)},
    triggers: ${JSON.stringify(e.triggers)},
    origin: ${JSON.stringify(e.origin)},
    enabled: ${e.enabled},
    body: \`${escTemplate(e.body)}\`,
  },`,
  )
  .join("\n")}
];
`;

writeFileSync(outFile, out);
console.log(`generated ${outFile} — ${entries.length} skills: ${entries.map((e) => e.slug).join(", ")}`);
